import { _electron as electron } from 'playwright'
import { mkdtempSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
const root = resolve(import.meta.dirname, '..')
const out = join(root, 'test-output')
const image = ['C:/Windows/Web/4K/Wallpaper/Windows/img0_1920x1200.jpg', 'C:/Windows/Web/Wallpaper/Spotlight/img14.jpg'].find(existsSync)
const app = await electron.launch({ args: [root], env: { ...process.env, CADENCE_PLUS_USER_DATA: mkdtempSync(join(tmpdir(), 'cplus-')), CADENCE_PLUS_TEST: '1', CADENCE_PLUS_NO_MAXIMIZE: '1' } })
const win = await app.firstWindow()
await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1600, 960))
await win.waitForFunction(() => !!window.__cadencePlus)
await win.evaluate((p) => window.__cadencePlus.D.openPaths([p]), image)
await win.waitForFunction(() => window.__cadencePlus.get().docs.length === 1)
await win.waitForTimeout(700)
await win.keyboard.press('o')
await win.locator('.tool-btn.active').click({ button: 'right' })
await win.waitForTimeout(300)
await win.screenshot({ path: join(out, '14-tool-groups.png') })
await win.keyboard.press('Escape')
await win.mouse.click(5, 5)
await win.evaluate(() => window.__cadencePlus.run('filter.unsharp'))
await win.waitForTimeout(600)
await win.screenshot({ path: join(out, '15-unsharp.png') })
await win.keyboard.press('Escape')
await win.evaluate(() => window.__cadencePlus.set({ fg: '#2a6fd0' }))
await win.evaluate(() => window.__cadencePlus.run('select.colorRange'))
await win.waitForTimeout(600)
await win.screenshot({ path: join(out, '16-color-range.png') })
await win.keyboard.press('Enter')
await win.waitForTimeout(300)
await win.keyboard.press('q')
await win.waitForTimeout(500)
await win.screenshot({ path: join(out, '17-quick-mask.png') })
await app.close()
